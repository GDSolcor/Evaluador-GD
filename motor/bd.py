"""Conexión a las bases del Evaluador: SQLite en el equipo o Postgres (Supabase) en la nube.

Si la variable EVALUADOR_DB_URL tiene una cadena de conexión de Postgres, cada base SQLite del Evaluador
se lee de un esquema de Postgres con el mismo contenido (lo carga herramientas/migrar_a_nube.py):

    usuarios.db -> ev_usuarios         evaluaciones.db -> ev_evaluaciones     leads.db -> ev_leads
    soporte.db  -> ev_soporte          capas (4 bases) -> ev_gis.features     catastro, hidrografía, rásteres ...

ConexionPg imita lo que el resto del código usa de sqlite3.Connection (execute, executemany, executescript,
with, lastrowid, filas que se leen por posición o por nombre), así que los módulos no cambian su SQL:
aquí se traducen los «?», json_extract, group_concat, pragma table_info y las consultas por recuadro
(xmax>=? AND xmin<=? ...) a un cruce de cajas con índice GiST.

Sin EVALUADOR_DB_URL todo sigue como siempre: conectar() devuelve sqlite3.connect(...).
"""
import os
import re
import sqlite3
import threading

URL = os.environ.get("EVALUADOR_DB_URL", "").strip()
NUBE = bool(URL)
COMUN = "ev_comun"  # funciones compartidas (ev_caja, sin_tildes)

_pool = None
_pool_lock = threading.Lock()
_cache_script = set()
_cache_cols = {}
Error = sqlite3.Error  # los módulos capturan sqlite3.Error; en la nube se envuelven los errores de Postgres


def _crear_pool():
    global _pool
    with _pool_lock:
        if _pool is None:
            import psycopg
            from psycopg_pool import ConnectionPool

            def configurar(con):
                con.autocommit = True
                con._ev_esquema = None

            _pool = ConnectionPool(
                URL, min_size=1, max_size=int(os.environ.get("EVALUADOR_DB_POOL", "8")), open=True,
                kwargs=dict(cursor_factory=psycopg.ClientCursor, prepare_threshold=None, connect_timeout=15),
                configure=configurar, timeout=60, max_idle=300)
    return _pool


def conectar(esquema, ruta_sqlite=None, **kw):
    """Conexión a la base lógica «esquema». En el equipo abre el archivo SQLite con los argumentos de siempre."""
    if not NUBE:
        return sqlite3.connect(ruta_sqlite, **kw)
    return ConexionPg(esquema)


def esquema_disponible(esquema, tabla):
    """En la nube: ¿se cargó la tabla? (reemplaza los os.path.isfile de las bases SQLite)."""
    try:
        return bool(_columnas(esquema, tabla))
    except Exception:
        return False


# --------------------------------------------------------------------------
# Traducción de SQL de SQLite a Postgres
# --------------------------------------------------------------------------

# recuadro «el elemento toca la ventana»: max>=a AND min<=b AND max>=c AND min<=d (o en orden min<=,max>=)
_N = r"(?:[A-Za-z_][\w]*\.)?"
_CAJA = re.compile(
    rf"(?P<p>{_N})(?P<X1>xmax|maxx|x1)\s*>=\s*\?\s+and\s+(?P=p)(?P<X0>xmin|minx|x0)\s*<=\s*\?\s+and\s+"
    rf"(?P=p)(?P<Y1>ymax|maxy|y1)\s*>=\s*\?\s+and\s+(?P=p)(?P<Y0>ymin|miny|y0)\s*<=\s*\?", re.I)
_CAJA_INV = re.compile(
    rf"(?P<p>{_N})(?P<X0>xmin|minx|x0)\s*<=\s*\?\s+and\s+(?P=p)(?P<X1>xmax|maxx|x1)\s*>=\s*\?\s+and\s+"
    rf"(?P=p)(?P<Y0>ymin|miny|y0)\s*<=\s*\?\s+and\s+(?P=p)(?P<Y1>ymax|maxy|y1)\s*>=\s*\?", re.I)
_JSON = re.compile(r"json_extract\(\s*([\w.]+)\s*,\s*'\$\.(\w+)'\s*\)", re.I)
_GCONCAT = re.compile(r"group_concat\(\s*([^,()]+?)\s*(?:,\s*('[^']*'))?\s*\)", re.I)
_PRAGMA = re.compile(r"^\s*pragma\s+table_info\(\s*[\"']?(\w+)[\"']?\s*\)\s*$", re.I)
_INSERT = re.compile(r"^\s*insert\s+(?:or\s+(ignore|replace)\s+)?into\s+[\"']?(\w+)[\"']?", re.I)
_TIPOS_CREATE = ((re.compile(r"\binteger\s+primary\s+key(\s+autoincrement)?", re.I),
                  "bigint generated by default as identity primary key"),)


def _caja(m, inv=False):
    p = m.group("p")
    cols = f"box(point({p}{m.group('X0')},{p}{m.group('Y0')}),point({p}{m.group('X1')},{p}{m.group('Y1')}))"
    return f"{cols} && {COMUN}.{'ev_caja_inv' if inv else 'ev_caja'}(?,?,?,?)"


def traducir(sql, con_parametros=True):
    s = sql
    s = _CAJA.sub(lambda m: _caja(m), s)
    s = _CAJA_INV.sub(lambda m: _caja(m, True), s)
    s = _JSON.sub(lambda m: f"({m.group(1)}::jsonb->>'{m.group(2)}')", s)
    s = _GCONCAT.sub(lambda m: f"string_agg(({m.group(1)})::text, {m.group(2) or chr(39) + ',' + chr(39)})", s)
    s = re.sub(r"\bifnull\(", "coalesce(", s, flags=re.I)
    s = re.sub(r"\blike\b", "ilike", s, flags=re.I)  # LIKE de SQLite no distingue mayúsculas (ASCII)
    s = re.sub(r"\bsin_tildes\(", f"{COMUN}.sin_tildes(", s, flags=re.I)
    m = _INSERT.match(s)
    if m and m.group(1):
        s = re.sub(r"^\s*insert\s+or\s+(ignore|replace)\s+into", "insert into", s, flags=re.I)
        if m.group(1).lower() == "ignore":
            s += " on conflict do nothing"
    # ? -> %s (los % literales se duplican primero); los ? dentro de cadenas no se tocan
    partes = re.split(r"('(?:[^']|'')*')", s)
    for i in range(0, len(partes), 2):
        # xmin/xmax son columnas de sistema en Postgres: la carga las guarda como xmin_/xmax_
        partes[i] = re.sub(r"\b(xmin|xmax)\b", r"\1_", partes[i], flags=re.I)
        if con_parametros:  # sin parámetros psycopg no interpreta los % (no se duplican)
            partes[i] = partes[i].replace("%", "%%").replace("?", "%s")
    if con_parametros:
        for i in range(1, len(partes), 2):
            partes[i] = partes[i].replace("%", "%%")
    return "".join(partes)


def _columnas(esquema, tabla):
    """Columnas de la tabla (nombre tal cual, p. ej. «Drenaje_Sencillo», o en minúsculas como queda sin comillas)."""
    clave = (esquema, tabla)
    if clave not in _cache_cols:
        with _pool_conexion(esquema) as con:
            filas = con.execute(
                "select column_name, data_type, is_nullable, column_default from information_schema.columns "
                "where table_schema=%s and table_name in (%s, lower(%s)) order by table_name = %s desc, ordinal_position",
                (esquema, tabla, tabla, tabla)).fetchall()
            if filas:  # si existen las dos variantes, solo la exacta
                exacta = con.execute("select 1 from information_schema.tables where table_schema=%s and table_name=%s",
                                     (esquema, tabla)).fetchone()
                if exacta and tabla != tabla.lower():
                    filas = con.execute(
                        "select column_name, data_type, is_nullable, column_default from information_schema.columns "
                        "where table_schema=%s and table_name=%s order by ordinal_position", (esquema, tabla)).fetchall()
        if not filas:
            return []
        _cache_cols[clave] = filas
    return _cache_cols[clave]


class _pool_conexion:
    """Toma una conexión del pool con search_path al esquema pedido."""

    def __init__(self, esquema):
        self.esquema = esquema

    def __enter__(self):
        self.ctx = _crear_pool().connection()
        con = self.ctx.__enter__()
        if getattr(con, "_ev_esquema", None) != self.esquema:
            con.execute(f"set search_path to {self.esquema}, {COMUN}, public")
            con._ev_esquema = self.esquema
        return con

    def __exit__(self, *exc):
        return self.ctx.__exit__(*exc)


class Fila(tuple):
    """Fila que se lee por posición o por nombre, como sqlite3.Row."""

    def __new__(cls, valores, nombres):
        f = super().__new__(cls, valores)
        f._nombres = nombres
        return f

    def keys(self):
        return list(self._nombres)

    def __getitem__(self, k):
        if isinstance(k, str):
            try:
                return tuple.__getitem__(self, self._nombres.index(k))
            except ValueError:
                raise IndexError(k) from None
        return tuple.__getitem__(self, k)


class CursorPg:
    """Resultado ya leído (lista), con la interfaz de sqlite3.Cursor que usa el Evaluador."""

    def __init__(self, filas=(), descripcion=None, lastrowid=None, rowcount=-1):
        self._filas, self._i = list(filas), 0
        self.description, self.lastrowid, self.rowcount = descripcion, lastrowid, rowcount

    def fetchone(self):
        if self._i >= len(self._filas):
            return None
        self._i += 1
        return self._filas[self._i - 1]

    def fetchall(self):
        r, self._i = self._filas[self._i:], len(self._filas)
        return r

    def fetchmany(self, n=1):
        r = self._filas[self._i:self._i + n]
        self._i += len(r)
        return r

    def __iter__(self):
        while self._i < len(self._filas):
            self._i += 1
            yield self._filas[self._i - 1]

    def close(self):
        pass


class ConexionPg:
    """Conexión «tipo sqlite3» sobre el pool de Postgres. Fuera de un bloque with cada sentencia se confirma
    sola; dentro de with es una transacción (commit al salir sin error, rollback si falla)."""

    def __init__(self, esquema):
        self.esquema = esquema
        self.row_factory = None
        self._ctx = self._con = self._tx = None
        self._prof = 0

    # -- transacciones --
    def __enter__(self):
        if self._prof == 0:
            self._ctx = _pool_conexion(self.esquema)
            self._con = self._ctx.__enter__()
            self._tx = self._con.transaction()
            self._tx.__enter__()
        self._prof += 1
        return self

    def __exit__(self, tipo, valor, tb):
        self._prof -= 1
        if self._prof == 0:
            try:
                self._tx.__exit__(tipo, valor, tb)
            finally:
                self._ctx.__exit__(tipo, valor, tb)
                self._ctx = self._con = self._tx = None
        return False

    def commit(self):
        pass

    def rollback(self):
        pass

    def close(self):
        pass

    def create_function(self, *a, **k):
        pass  # sin_tildes ya existe en Postgres (ev_comun.sin_tildes)

    def cursor(self):
        return self

    # -- sentencias --
    def _ejecutar(self, con, sql, params):
        m = _PRAGMA.match(sql)
        if m:
            cols = _columnas(self.esquema, m.group(1))
            return CursorPg([(i, c[0], c[1], int(c[2] == "NO"), c[3], 0) for i, c in enumerate(cols)])
        q = traducir(sql, params is not None)
        ins = _INSERT.match(sql)
        if ins and " returning " not in q.lower():
            cols = [c[0] for c in _columnas(self.esquema, ins.group(2))]
            if "id" in cols:
                q += " returning id"
        cur = con.execute(q, tuple(params) if params is not None else None)
        filas, desc, lastrowid = [], cur.description, None
        if desc:
            nombres = [d.name for d in desc]
            filas = [Fila(r, nombres) for r in cur.fetchall()]
            if ins:
                lastrowid = filas[0][0] if filas else None
                filas, desc = [], None
        if re.match(r"^\s*alter\s+table", sql, re.I):
            _cache_cols.clear()
        return CursorPg(filas, desc, lastrowid, cur.rowcount)

    def execute(self, sql, params=None):
        try:
            if self._con is not None:
                return self._ejecutar(self._con, sql, params)
            with _pool_conexion(self.esquema) as con:
                return self._ejecutar(con, sql, params)
        except Exception as e:
            if e.__class__.__module__.startswith("psycopg"):
                raise sqlite3.OperationalError(f"{e.__class__.__name__}: {e}") from e
            raise

    def executemany(self, sql, filas):
        filas = list(filas)
        if self._con is not None:
            for f in filas:
                self.execute(sql, f)
        else:
            with self:
                for f in filas:
                    self.execute(sql, f)
        return CursorPg()

    def executescript(self, script):
        """Solo se usa para crear tablas e índices «if not exists»: se ejecuta una vez por proceso."""
        clave = (self.esquema, script)
        if clave in _cache_script:
            return CursorPg()
        for s in [x.strip() for x in script.split(";") if x.strip()]:
            for rx, rep in _TIPOS_CREATE:
                s = rx.sub(rep, s)
            self.execute(s)
        _cache_script.add(clave)
        return CursorPg()


