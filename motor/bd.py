def guardar_archivo(ruta, datos):
    with ConexionPg("ev_archivos") as c:
        c.execute("insert into archivos(ruta, datos) values (?, ?) on conflict (ruta) do update set datos=excluded.datos",
                  (ruta, datos))


def leer_archivo(ruta):
    r = ConexionPg("ev_archivos").execute("select datos from archivos where ruta=?", (ruta,)).fetchone()
    return bytes(r[0]) if r else None


def borrar_archivo(ruta):
    ConexionPg("ev_archivos").execute("delete from archivos where ruta=?", (ruta,))


def espejo_archivos(carpetas, cada_s=10):
    """En la nube el disco del contenedor se pierde al reiniciar: los archivos que la herramienta escribe en estas
    carpetas (módulos.json, fuentes.json, config_correo.json, fichas de módulos …) se copian a ev_archivos.archivos.
    Al arrancar se restauran; luego un hilo sube cada cada_s segundos los que cambiaron."""
    if not NUBE:
        return
    import time

    def clave(carpeta, nombre):
        return "espejo/" + os.path.basename(os.path.normpath(carpeta)) + "/" + nombre

    vistos = {}
    for carpeta in carpetas:
        os.makedirs(carpeta, exist_ok=True)
        prefijo = clave(carpeta, "")
        for ruta, datos in ConexionPg("ev_archivos").execute(
                "select ruta, datos from archivos where ruta like ?", (prefijo.replace("_", "\\_") + "%",)):
            destino = os.path.join(carpeta, ruta[len(prefijo):])
            with open(destino, "wb") as f:
                f.write(bytes(datos))
            vistos[destino] = os.path.getmtime(destino)

    def vigilar():
        while True:
            time.sleep(cada_s)
            for carpeta in carpetas:
                try:
                    nombres = [n for n in os.listdir(carpeta) if os.path.isfile(os.path.join(carpeta, n))
                               and not n.endswith((".tmp", ".db", ".db-journal", ".log"))]
                except OSError:
                    continue
                for n in nombres:
                    ruta = os.path.join(carpeta, n)
                    try:
                        m = os.path.getmtime(ruta)
                        if vistos.get(ruta) != m:
                            with open(ruta, "rb") as f:
                                guardar_archivo(clave(carpeta, n), f.read())
                            vistos[ruta] = m
                    except Exception as e:  # nunca tumbar el servidor por el espejo
                        print(f"Aviso: no se pudo guardar {ruta} en la base ({type(e).__name__}: {e})")

    threading.Thread(target=vigilar, daemon=True, name="espejo_archivos").start()


def restaurar_estaticos(datos):
    """Escribe en datos/ los archivos pequeños que no van en git (GeoTIFF de PVOUT, conteos, caché del mapa),
    guardados por herramientas/migrar_a_nube.py en ev_archivos.archivos con la clave estaticos/<ruta>."""
    if not NUBE:
        return 0
    n = 0
    for ruta, datos_archivo in ConexionPg("ev_archivos").execute(
            "select ruta, datos from archivos where ruta like 'estaticos/%' order by ruta = 'estaticos/cache_pvout.png'"):
        destino = os.path.join(datos, *ruta[len("estaticos/"):].split("/"))
        if not os.path.isfile(destino):
            os.makedirs(os.path.dirname(destino), exist_ok=True)
            with open(destino, "wb") as f:
                f.write(bytes(datos_archivo))
            n += 1
    return n
